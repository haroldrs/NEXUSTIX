"""Create the first administrator; never runs during service startup.

Interactive (asks for the password twice):
    python bootstrap_admin.py --email admin@example.com

Non-interactive (automation of an isolated environment; the file is a Docker
secret generated by scripts/generar_secretos.py and is never printed):
    python bootstrap_admin.py --email admin@example.com --password-file /run/secrets/admin_password
"""

import argparse
import os
import secrets
import stat
from getpass import getpass
from pathlib import Path

from argon2 import PasswordHasher
from pydantic import EmailStr, TypeAdapter, ValidationError
from sqlalchemy import func, text
from sqlalchemy.exc import IntegrityError

from database import SessionLocal
from models import Usuario

EMAIL_ADAPTER = TypeAdapter(EmailStr)
PASSWORDS = PasswordHasher()
REVISION = "20261102_02"


def _password_from_file(parser: argparse.ArgumentParser, path: Path) -> str:
    try:
        mode = path.stat().st_mode
        password = path.read_text(encoding="utf-8").strip()
    except OSError:
        parser.error("No se pudo leer el archivo de contraseña indicado")
    if os.name == "posix" and mode & (stat.S_IRWXG | stat.S_IRWXO) and not str(path).startswith("/run/secrets/"):
        parser.error("El archivo de contraseña no debe ser legible por otros usuarios (use modo 0600)")
    return password


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--email", help="Correo validado del administrador inicial")
    parser.add_argument("--password-file", type=Path, help="Archivo con la contraseña inicial (modo no interactivo)")
    parser.add_argument("--if-missing", action="store_true",
                        help="Terminar con éxito sin cambios si ya existe un administrador con ese correo")
    args = parser.parse_args()
    email_input = args.email or input("Correo del administrador: ")
    try:
        email = str(EMAIL_ADAPTER.validate_python(email_input.strip())).lower()
    except ValidationError:
        parser.error("El correo no tiene un formato válido")
    if args.password_file:
        password = confirmation = _password_from_file(parser, args.password_file)
    else:
        password = getpass("Contraseña inicial (mínimo 12 caracteres): ")
        confirmation = getpass("Repite la contraseña: ")
    if len(password) < 12 or len(password) > 256 or not secrets.compare_digest(password, confirmation):
        parser.error("Contraseñas no válidas o distintas; mínimo 12 y máximo 256 caracteres")

    db = SessionLocal()
    try:
        revision = db.execute(text("SELECT version_num FROM alembic_version")).scalar_one_or_none()
        if revision != REVISION:
            parser.error("Ejecuta primero las migraciones autorizadas de Usuarios")
        db.execute(text("SELECT pg_advisory_xact_lock(741925103)") )
        existing_admin = db.query(Usuario).filter(Usuario.role == "administrador").first()
        if existing_admin:
            if args.if_missing and existing_admin.email.strip().lower() == email:
                print(f"El administrador ya existe (ID {existing_admin.id}); no se realizaron cambios.")
                return 0
            parser.error("Ya existe un administrador; el bootstrap inicial no se repetirá")
        if db.query(Usuario.id).filter(func.lower(Usuario.email) == email).first():
            parser.error("El correo ya está asociado a una cuenta existente; no se reclamará automáticamente")
        admin = Usuario(
            nombre="Administrador NEXUSTIX",
            email=email,
            estado="activo",
            password_hash=PASSWORDS.hash(password),
            role="administrador",
            auth_status="active",
        )
        db.add(admin)
        db.commit()
        print(f"Administrador creado con ID {admin.id}. Guarda el acceso en el gestor de secretos aprobado.")
        return 0
    except IntegrityError:
        db.rollback()
        parser.error("No se pudo crear la cuenta; verifica correo único y migración")
    finally:
        db.close()
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
